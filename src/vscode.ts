// Point VS Code's TypeScript 7 extension at the project's own tsrs (oxc-project/tsrs#661), reversibly.

import { applyEdits, modify, parse, type ParseError } from "jsonc-parser";
import { chmodSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { binaryVersion, DoctorError } from "./resolve.ts";

export const TSDK_DIR = ".vscode/tsrs-tsdk";
const SETTINGS = ".vscode/settings.json";
const BACKUP = `${TSDK_DIR}/backup.json`;
const SETTINGS_COPY = `${TSDK_DIR}/settings.json.bak`;

/** Settings written by `tsrs-doctor vscode`. The extension resolves a relative tsdk path against the workspace root. */
export const SETTINGS_TO_WRITE: Record<string, unknown> = {
  "js/ts.tsdk.path": TSDK_DIR,
  "js/ts.experimental.useTsgo": true,
};

// No absolute paths: the script finds node_modules relative to itself, so it can be committed.
const SHIM = `#!/bin/sh
# Generated by tsrs-doctor. VS Code's TypeScript 7 extension runs "<js/ts.tsdk.path>/tsgo --lsp --stdio".
root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
exec "$root/node_modules/.bin/tsrs" "$@"
`;

interface Backup {
  settingsExisted: boolean;
  /** Previous value per key; a missing entry means the key was absent. */
  previous: Record<string, unknown>;
}

const FORMAT = { formattingOptions: { insertSpaces: true, tabSize: 2, eol: "\n" } };

function readSettings(path: string): { text: string; value: Record<string, unknown> } {
  const text = readFileSync(path, "utf8");
  const errors: ParseError[] = [];
  const value = parse(text, errors, { allowTrailingComma: true });
  if (errors.length || typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new DoctorError(`${path} is not a valid JSON object; fix it before running tsrs-doctor vscode.`);
  }
  return { text, value };
}

function setKeys(text: string, entries: Record<string, unknown>): string {
  for (const [key, value] of Object.entries(entries)) text = applyEdits(text, modify(text, [key], value, FORMAT));
  return text;
}

export function setupVscode(root: string, log: (s: string) => void = console.log): void {
  if (process.platform === "win32") throw new DoctorError("tsrs has no Windows binary yet (oxc-project/tsrs#676).");
  if (!existsSync(join(root, "node_modules", "tsrs", "package.json"))) {
    throw new DoctorError(`No node_modules/tsrs in ${root}. Run \`bun add -d tsrs\` (or your package manager) first.`);
  }
  const settingsPath = join(root, SETTINGS);
  const settingsExisted = existsSync(settingsPath);
  const { text, value } = settingsExisted ? readSettings(settingsPath) : { text: "{}\n", value: {} };

  mkdirSync(join(root, TSDK_DIR), { recursive: true });
  const backupPath = join(root, BACKUP);
  if (existsSync(backupPath)) {
    log(`Backup already present at ${BACKUP}; keeping the original one.`);
  } else {
    const previous: Record<string, unknown> = {};
    for (const key of Object.keys(SETTINGS_TO_WRITE)) if (key in value) previous[key] = value[key];
    const backup: Backup = { settingsExisted, previous };
    if (settingsExisted) writeFileSync(join(root, SETTINGS_COPY), text);
    writeFileSync(backupPath, JSON.stringify(backup, null, 2) + "\n");
    // The backup is per-machine state; the shim and settings are what a team commits.
    writeFileSync(join(root, TSDK_DIR, ".gitignore"), "backup.json\nsettings.json.bak\n");
  }

  const shimPath = join(root, TSDK_DIR, "tsgo");
  writeFileSync(shimPath, SHIM);
  chmodSync(shimPath, 0o755);
  writeFileSync(settingsPath, setKeys(text, SETTINGS_TO_WRITE));

  const version = binaryVersion(shimPath);
  if (!version.includes("tsrs")) {
    throw new DoctorError(`${shimPath} --version printed "${version}", which is not tsrs.`);
  }
  log(`Wrote ${TSDK_DIR}/tsgo and ${SETTINGS} (${Object.keys(SETTINGS_TO_WRITE).join(", ")}).`);
  log(`Checked: ${TSDK_DIR}/tsgo --version -> ${version}`);
  log(
    [
      "Next in VS Code:",
      "  1. Install the TypeScript 7 extension (TypeScriptTeam.native-preview).",
      "  2. Trust the workspace and accept the prompt to use the workspace TypeScript version.",
      '  3. Run "TypeScript 7: Restart Server"; the "TypeScript 7" output channel names the executable.',
      "Undo with: tsrs-doctor vscode --undo",
    ].join("\n"),
  );
}

export function undoVscode(root: string, log: (s: string) => void = console.log): void {
  const backupPath = join(root, BACKUP);
  if (!existsSync(backupPath)) throw new DoctorError(`No ${BACKUP} in ${root}; nothing to undo.`);
  const backup: Backup = JSON.parse(readFileSync(backupPath, "utf8"));
  const settingsPath = join(root, SETTINGS);

  if (existsSync(settingsPath)) {
    let { text } = readSettings(settingsPath);
    // Restore only our keys, so edits made after setup survive.
    for (const key of Object.keys(SETTINGS_TO_WRITE)) {
      text = applyEdits(text, modify(text, [key], key in backup.previous ? backup.previous[key] : undefined, FORMAT));
    }
    const remaining = parse(text, [], { allowTrailingComma: true }) ?? {};
    if (!backup.settingsExisted && Object.keys(remaining).length === 0) {
      rmSync(settingsPath);
      log(`Removed ${SETTINGS} (it did not exist before setup).`);
    } else {
      writeFileSync(settingsPath, text);
      log(`Restored ${Object.keys(SETTINGS_TO_WRITE).join(", ")} in ${SETTINGS}.`);
    }
  }
  rmSync(join(root, TSDK_DIR), { recursive: true, force: true });
  log(`Removed ${TSDK_DIR}/.`);
}
